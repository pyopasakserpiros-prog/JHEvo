'use strict';
const assert=require('assert'),G=require('./load');require('../js/ui');
const {SIM,SECT,UI,HC}=G,W=SIM.create('lineage-history'),[a,b,c]=W.npcs;
const m=SECT.MENTORSHIP;
assert(m.formBond(W,a,b,{force:true}).ok);
assert.strictEqual(m.ensure(W).history.length,1,'bond recorded');
assert(m.formBond(W,a,b,{force:true}).ok);
assert.strictEqual(m.ensure(W).history.length,1,'repeated bond is idempotent');
assert(m.formBond(W,c,b,{force:true}).ok);
assert(!a.apprenticeIds.includes(b.id),'old mentor should no longer hold transferred apprentice');
assert.strictEqual(m.formBond(W,b,c,{force:true}).ok,false,'cycles are rejected');
const sent=m.transmitQi(W,c,b,{force:true});assert(sent.ok);
assert(m.ensure(W).history.some(x=>x.kind==='transmission'&&x.mentorId===c.id&&x.discipleId===b.id));
const save=SIM.serialize(W),R=SIM.deserialize(save);assert(R.sect.mentorship.history.some(x=>x.kind==='transmission'));
UI.G={W:R,R:{},opts:{},acc:0,speed:1};UI.tab='all'; UI.logFilters=new Set(['all']);
assert(UI.rLog().includes('พงศาวดารสายสืบทอด'));
UI.npcId=b.id; UI.tab='ov'; assert(UI.rNpc().includes('ประวัติสายสืบทอดของคนนี้'));
assert(UI.lineageHistory(R,b.id).includes('ถ่ายทอดปราณ'));
assert(!UI.lineageHistory(R,a.id).includes('ถ่ายทอดปราณ'), 'personal history excludes other people');
assert(UI.lineageHistory(R,b.id).includes(c.h.name.given));
assert(R.sect.mentorship.history.some(x=>x.mentorNameTh===HC.fullName(c)));
assert.strictEqual(m.coachDisciple(R,R.byId[b.id],R.byId[c.id]).ok,false,'coaching cannot create a cycle');
R.byId[c.id].dead=true; assert(UI.lineageHistory(R,b.id).includes(HC.fullName(c)), 'history keeps names after death');
const empty=SIM.create('lineage-no-fabrication'); assert.strictEqual(m.ensure(empty).history.length,0,'old worlds must not invent events');
for(let i=0;i<205;i++) m.recordHistory(empty,'bond',empty.npcs[0],empty.npcs[1]);
assert.strictEqual(m.ensure(empty).history.length,200,'history remains bounded');
console.log('PASS lineage history, reassignment, cycles, real transmission and save/load');
