'use strict';
const assert = require('assert');
const { bootGame } = require('./_harness');
const w = bootGame(203201);
const { SIM, SECT, EXP, HC } = w;
const W = SIM.newWorld(203201);
assert.strictEqual(HC.FINGERPRINT, '155:2f9c9dd7', 'HumanCore lock verified');
const motion = SECT.COUNCIL.proposeMotion(W, 'DOCTRINE_ORTHODOX_PURITY', W.members[0]);
assert.ok(motion && motion.status === 'RESOLVED', 'Council motion resolved');
EXP.RESOURCE_NODES.ensureNodes(W);
const nodes = Object.values(W.jianghu.resourceNodes);
assert.strictEqual(nodes.length, 6, '6 Resource nodes initialized');
const capRes = EXP.RESOURCE_NODES.captureNodeForSect(W, nodes[0].id, W.members.slice(0, 3), 25);
assert.ok(capRes && capRes.ok, 'Sect captured resource node');
const assem = EXP.MARTIAL_ASSEMBLY.conveneAssembly(W, 'TOURNAMENT_HEGEMONY');
assert.ok(assem && assem.status === 'RESOLVED', 'Martial assembly resolved');
const dirEval = SIM.HEAVENLY_DIRECTOR.evaluateWorldTension(W);
assert.ok(typeof dirEval.tension === 'number', 'Director tension evaluated');
console.log('ALL v2.0.32 COUNCIL, RESOURCE NODES, MARTIAL ASSEMBLY & DIRECTOR TESTS PASSED!');
