'use strict';
const assert = require('assert');
const { bootGame } = require('./_harness');
const w = bootGame(203301);
const { SIM, SECT, CULT, EXP, COG, AI, UI, HC } = w;
const W = SIM.newWorld(203301);
assert.ok((SIM.PATCH_VERSION === '3.0.0' || SIM.PATCH_VERSION === '3.1.0' || SIM.PATCH_VERSION === '3.1.1' || (SIM.PATCH_VERSION === '3.2.0' || (SIM.PATCH_VERSION === '3.3.0' || (SIM.PATCH_VERSION === '3.4.0' || (SIM.PATCH_VERSION === '4.0.0' || SIM.PATCH_VERSION === '5.2.0'))))) || SIM.PATCH_VERSION === '2.0.33', 'Patch version verified');
assert.strictEqual(HC.FINGERPRINT, '155:2f9c9dd7', 'HumanCore fingerprint preserved');
assert.strictEqual(Object.keys(SECT.PEAKS.PEAK_CATALOG).length, 8, '8 canonical peaks locked');
const visibleInitially = SECT.PEAKS.getFoundedPeaks(W);
assert.strictEqual(visibleInitially.length, 0, 'Unfounded peaks hidden by default');
const elderCand = W.members.find(m => m.alive && !m.inSect && m.rank < 4) || W.members[3];
elderCand.realm = 4; elderCand.rank = 3; elderCand.inSect = null; elderCand.contrib = 500;
const promRes = SECT.ELDER_STATUS.promoteToElderStatus(W, elderCand, 'BROKE_THROUGH_CORE');
assert.ok(promRes && promRes.ok && elderCand.rank >= 4 && elderCand.isElder === true && !elderCand.inSect, 'Unappointed Elder promoted cleanly');
const xianMembers = W.members.slice(0, 4);
xianMembers.forEach((m, idx) => { m.alive = true; m.path = 'XIAN'; m.peakId = null; if (idx === 0) { m.rank = 4; m.isElder = true; } });
const foundXian = SECT.PEAKS.foundPeak(W, 'PEAK_AZURE_SWORD');
assert.ok(foundXian && foundXian.ok, 'PEAK_AZURE_SWORD founded');
const demonMembers = W.members.slice(4, 8);
demonMembers.forEach((m, idx) => { m.alive = true; m.path = 'DEMON'; m.peakId = null; if (idx === 0) { m.rank = 4; m.isElder = true; } });
const foundDemon = SECT.PEAKS.foundPeak(W, 'PEAK_CRIMSON_SHADOW');
assert.ok(foundDemon && foundDemon.ok, 'PEAK_CRIMSON_SHADOW founded');
const allocRes = SECT.PEAKS.allocateCentralResources(W);
assert.ok(allocRes && allocRes.ok && allocRes.distributedTotal > 0, 'Central-to-Peak allocation succeeded');
const tourneyRes = SECT.PEAKS.holdInterPeakTournament(W);
assert.ok(tourneyRes && tourneyRes.ok && tourneyRes.champion, 'Inter-Peak tournament completed');
const xianM = xianMembers[1];
const demonM = demonMembers[1];
const scoreBefore = SECT.relationScore(W, xianM, demonM);
SECT.SOCIAL_MATRIX.applyActionModifier(W, xianM, demonM, 'LIFE_AND_DEATH_TRIBULATION', { placeTh: 'แดนลับบรรพกาล' });
const scoreAfter = SECT.relationScore(W, xianM, demonM);
assert.ok(scoreAfter > scoreBefore + 25, 'Life-and-death survival bond overcomes Inter-Peak feud');
console.log('ALL v2.0.33 PEAKS, ELDER STATUS, SOCIAL MATRIX & COGNITION TESTS PASSED!');
