'use strict';
const assert = require('assert');
const G = require('./load');
require('../js/ui');
const { SIM, EXPED, EXPLORE, UI } = G;
const W = SIM.create('world-atlas-coverage');
assert.strictEqual(typeof UI.buildWorldAtlas, 'function', 'the atlas must provide a real world-data model');
const atlas = UI.buildWorldAtlas(W);
const get = id => atlas.nodes.find(n => n.id === id);
const topology = EXPED.ensureWorldTopology(W);
for (const node of Object.values(topology.nodes)) assert(get(node.id), `missing topology destination ${node.id}`);
for (const [rank, sites] of Object.entries(EXPED.FORTUNE_REGISTRY)) for (const site of sites) {
  const node = get('FORTUNE:' + site.id);
  assert(node && node.fortuneRank === +rank && node.approximate, `fortune discovery ${site.id} must be represented without inventing its exact location`);
}
for (const id of Object.keys(EXPLORE.SANCTUMS)) assert(get(id), `missing sanctum ${id}`);
assert(get('ATLAS_DIMENSION_GATE'), 'the actual dimensional gate must be represented');
const mangrove = get('SRC110_MW_ENV_02_MIASMA_MANGROVE');
assert.strictEqual(mangrove.macroRegion, 'SOUTHERN_WATERS');
const volcanic = get('SRC110_MW_ENV_04_VOLCANIC_CALDERA');
assert.strictEqual(volcanic.macroRegion, 'WESTERN_BADLANDS');
for (const sect of W.world.allSects) assert(get(sect.nodeId) && get(sect.nodeId).alignment === sect.alignment);
for (const legend of W.world.wanderingLegends.filter(l => l && !l.dead)) {
  const pin = get('LEGEND:' + legend.id);
  assert(pin && pin.approximate && pin.macroRegion === legend.macroRegion, 'living wandering legends should appear in their known region without inventing their exact location');
}
for (const kind of ['sanctum', 'nine_dao_pagoda', 'elemental_realm']) {
  assert(EXPED.MISSIONS[kind] && EXPED.MISSIONS[kind].nameTh, `${kind} needs a mission label when members travel`);
}
for (const [kind, depart] of [
  ['sanctum', (world, members) => EXPLORE.departSanctum(world, members, 'SANCTUM_SWORD_ABYSS')],
  ['nine_dao_pagoda', (world, members) => EXPLORE.departNineDaoPagoda(world, members)],
  ['elemental_realm', (world, members) => EXPLORE.departElementalRealm(world, members)]
]) {
  const world = SIM.create('atlas-trial-ui-' + kind), members = world.npcs.slice(0, 1);
  const ex = depart(world, members);
  assert(ex, `${kind} departure should succeed`);
  members.forEach(n => { n.away = true; n.travel = null; });
  ex.state = 'away';
  UI.G = {W:world, R:{}, opts:{}, acc:0, speed:1}; UI.tab = 'exp';
  assert(UI.actText(members[0]).includes(EXPED.MISSIONS[kind].nameTh), `${kind} must display the member's activity`);
  assert(UI.rWorld().includes(EXPED.MISSIONS[kind].nameTh), `${kind} must appear in the travel list`);
  world.t = ex.ret; EXPED.hourly(world);
  assert(ex.done, `${kind} must settle at the destination`);
  assert(UI.rWorld().includes(EXPED.MISSIONS[kind].nameTh), `${kind} must remain readable after returning`);
}
const before = W.rng.getState().slice();
UI.buildWorldAtlas(W);
assert.deepStrictEqual(W.rng.getState(), before, 'drawing must never consume simulation randomness');
const clustered = UI.atlasGroups(atlas.nodes, 1);
const zoomed = UI.atlasGroups(atlas.nodes, 4);
assert(zoomed.length > clustered.length, 'zooming in must reveal locations hidden in clusters');
assert.strictEqual(clustered.reduce((sum, group) => sum + group.nodes.length, 0), atlas.nodes.length, 'clustering must retain every destination');
const party = W.npcs.filter(n => !n.dead && !n.away && !n.expId).sort((a,b) => G.CULT.power(b)-G.CULT.power(a)).slice(0, 3);
const an = EXPED.spawnWorldAnomaly(W, { macroRegion:'NORTHERN_PEAKS', durationDays:20 });
const expected = EXPED.estimateTravelTime(W, party, an.id, {baseDays:an.baseDays, useSectPhoenixAura:true});
const actual = UI.atlasTravelInfo(W, get(an.id) || UI.buildWorldAtlas(W).nodes.find(n => n.id === an.id), party);
assert.strictEqual(actual.days, expected.days, 'timed event estimate must match expedition calculation');
assert.strictEqual(UI.atlasTravelInfo(W, get('SANCTUM_SWORD_ABYSS'), party).days, 1.5, 'sanctum travel matches actual departure');
assert.strictEqual(UI.atlasTravelInfo(W, get('ATLAS_DIMENSION_GATE'), party).days, 0, 'the gate is inside the player sect');
const realm = EXPED.spawnSecretRealm ? EXPED.spawnSecretRealm(W, null, {quiet:true}) : null;
if (realm) assert(UI.buildWorldAtlas(W).nodes.some(n => n.templateId === realm.templateId && n.realmId === realm.id && n.active));
assert.strictEqual(typeof EXPED.departResourceClaim, 'function', 'resource capture should be a real expedition');
const available = W.npcs.filter(n => !n.dead && !n.away && !n.expId && !n.travel).slice(0, 2);
assert(available.length, 'test world must contain an available party');
const resource = Object.values(W.world.resourceNodes).find(n => n.ownerSectId !== 'PLAYER');
const ownerBefore = resource.ownerSectId;
const claim = EXPED.departResourceClaim(W, resource.id, available);
assert(claim.ok && claim.queued && claim.expedition.kind === 'resource_claim', 'capture must depart rather than resolve instantly');
assert.strictEqual(resource.ownerSectId, ownerBefore, 'owner cannot change before arrival');
assert.strictEqual(claim.expedition.ret - claim.expedition.t0, Math.round(claim.travel.days * 1440));
assert(available.every(n => n.expId === claim.expedition.id && n.away));
UI.G = {W, R:{}, opts:{}, acc:0, speed:1}; UI.tab = 'exp';
assert(UI.rWorld().includes(resource.nameTh), 'the travel list must name the resource target instead of a placeholder');
assert.strictEqual(EXPED.departResourceClaim(W, resource.id, available).ok, false, 'a second expedition cannot target the same claim');
W.t = claim.expedition.ret;
EXPED.hourly(W);
assert(claim.expedition.done && available.every(n => !n.away && !n.expId), 'arrival must resolve and release the party');
const lost = SIM.create('world-atlas-defended-claim');
const defended = Object.values(lost.world.resourceNodes).find(n => n.ownerSectId !== 'PLAYER');
defended.garrison.defensePower = 1e12;
const lostOwner = defended.ownerSectId;
const attacking = lost.npcs.filter(n => !n.dead && !n.away && !n.expId && !n.travel).slice(0, 1);
const failed = EXPED.departResourceClaim(lost, defended.id, attacking);
lost.t = failed.expedition.ret;
EXPED.hourly(lost);
assert.strictEqual(defended.ownerSectId, lostOwner, 'an overwhelmingly stronger garrison must not be captured automatically');
const W2 = SIM.create('world-atlas-site');
const members = W2.npcs.filter(n => !n.dead && !n.away && !n.expId && !n.travel);
const rank = Math.max(1, ...members.map(n => G.CULT.worldRank(n)));
const site = EXPED.FORTUNE_REGISTRY[rank][0];
const region = EXPED.REGIONS.find(r => r.terrain === site.biome || (site.biome === 'ruins' && r.id === 'ruins'));
assert(region, 'site must have a corresponding existing expedition region');
const journey = EXPED.depart(W2, members, 'fortune', region, {siteId:site.id});
assert(journey && journey.siteId === site.id, 'selecting a fortune site must target that exact site');
const invalidWorld = SIM.create('world-atlas-invalid-site');
const invalidParty = invalidWorld.npcs.filter(n => !n.dead && !n.away && !n.expId && !n.travel);
const invalidSeq = invalidWorld.world.seq, invalidRng = invalidWorld.rng.getState().slice();
assert.strictEqual(EXPED.depart(invalidWorld, invalidParty, 'fortune', EXPED.REGIONS[0], {siteId:'NOT_A_REAL_SITE'}), null);
assert.strictEqual(invalidWorld.world.seq, invalidSeq, 'an invalid target must not start an expedition');
assert.deepStrictEqual(invalidWorld.rng.getState(), invalidRng, 'rejecting an invalid target must not consume randomness');
assert(invalidParty.every(n => !n.expId && !n.away), 'an invalid target must not send members away');
const siegeWorld = SIM.create('world-atlas-siege');
const siegeNode = UI.buildWorldAtlas(siegeWorld).nodes.find(n => n.kind === 'NEIGHBOR_SECT' && !n.isVassal);
const siegeParty = UI.atlasParty(siegeWorld, siegeNode);
const siegeEstimate = UI.atlasTravelInfo(siegeWorld, siegeNode, siegeParty);
const siege = EXPED.marshalStrikeForce(siegeWorld, siegeParty, siegeNode.sectId, {immediate:false});
assert(siege.ok && siege.queued && !siege.siege.won, 'siege must not resolve at the moment it is dispatched');
assert.strictEqual(siege.travel.days, siegeEstimate.days, 'siege dispatch duration must match the map estimate');
assert.strictEqual(EXPED.marshalStrikeForce(siegeWorld, siegeParty, siegeNode.sectId, {immediate:false}).ok, false, 'duplicate siege must be rejected');
const vassalWorld = SIM.create('world-atlas-distress');
EXPED.ensureWorldTopology(vassalWorld);
const vassal = vassalWorld.world.allSects[0];
vassal.isVassal = true;
const distress = EXPED.spawnVassalDistressCall(vassalWorld, vassal.id);
assert(distress && !distress.resolved, 'vassal distress fixture must exist');
UI.atlasSelectedId = vassal.nodeId;
const vassalMap = UI.rWorldMap(vassalWorld);
assert(vassalMap.includes('atlas-alert') && vassalMap.includes('respond-vassal-distress'), 'active requests and their response controls must remain reachable from the atlas');
UI.atlasSelectedId = null;
const anomalyWorld = SIM.create('world-atlas-anomaly');
const anomaly = EXPED.spawnWorldAnomaly(anomalyWorld, {durationDays:20});
const anomalyNode = UI.buildWorldAtlas(anomalyWorld).nodes.find(n => n.anomalyId === anomaly.id);
const anomalyParty = UI.atlasParty(anomalyWorld, anomalyNode);
const anomalyEstimate = UI.atlasTravelInfo(anomalyWorld, anomalyNode, anomalyParty);
const anomalyTrip = EXPED.departWorldAnomaly(anomalyWorld, anomalyParty, anomaly.id, {immediate:false});
assert(anomalyTrip.ok && anomalyTrip.queued && !anomaly.resolved, 'anomaly must not resolve at departure');
assert.strictEqual(anomalyTrip.travel.days, anomalyEstimate.days, 'anomaly duration must match the map estimate');
assert.strictEqual(EXPED.departWorldAnomaly(anomalyWorld, anomalyParty, anomaly.id, {}).ok, false, 'duplicate anomaly expedition must be rejected');
anomaly.resolved = true; anomaly.expired = true; anomaly.claimedBy = anomaly.rivalSectId;
const stonesBeforeExpiry = anomalyWorld.sect.stones;
anomalyWorld.t = anomalyTrip.expedition.ret;
EXPED.hourly(anomalyWorld);
assert(anomalyTrip.expedition.done && anomalyParty.every(n => !n.away && !n.expId), 'an expired event must return its party rather than leave it away forever');
assert.strictEqual(anomalyWorld.sect.stones, stonesBeforeExpiry, 'an expired event must not grant rewards');
const victoryWorld = SIM.create('world-atlas-unopposed-claim');
const victoryNode = Object.values(victoryWorld.world.resourceNodes).find(n => n.ownerSectId !== 'PLAYER');
victoryNode.garrison.defensePower = 1;
const victoryParty = victoryWorld.npcs.filter(n => !n.dead && !n.away && !n.expId && !n.travel).slice(0, 1);
const victory = EXPED.departResourceClaim(victoryWorld, victoryNode.id, victoryParty);
victoryWorld.t = victory.expedition.ret;
EXPED.hourly(victoryWorld);
assert.strictEqual(victoryNode.ownerSectId, 'PLAYER', 'a successful claim changes ownership at arrival');
const fameAfter = victoryWorld.sect.fame;
EXPED.hourly(victoryWorld);
assert.strictEqual(victoryWorld.sect.fame, fameAfter, 'settlement cannot be repeated');
console.log('PASS world atlas coverage, authoritative geography, truthful travel and RNG stability');
