'use strict';
const assert = require('assert');
const { bootGame } = require('./_harness');
const w = bootGame(203101);
const { SIM, CULT, EXP, SECT } = w;
const W = SIM.newWorld(203101);
const m1 = W.members[0];
const m2 = W.members[1];
const knot = CULT.HEART_DEMON.formObsessionKnot(W, m1, 'TRIBULATION_TRAUMA', { targetId: m2.id, severity: 35 });
assert.ok(knot && knot.id, 'Obsession knot created');
assert.ok(EXP.ESPIONAGE && typeof EXP.ESPIONAGE.dispatchMission === 'function', 'EXP.ESPIONAGE exists');
assert.ok(SECT.CODEX_EVOLUTION && typeof SECT.CODEX_EVOLUTION.tryDeriveCodex === 'function', 'SECT.CODEX_EVOLUTION exists');
const cal = EXP.CALAMITY.spawnCalamity(W, 'ABYSSAL_BEAST_TIDE');
assert.ok(cal && cal.active, 'Calamity spawned');
console.log('ALL v2.0.31 STRATEGIC PROPOSAL FLAGSHIPS TESTS PASSED!');
