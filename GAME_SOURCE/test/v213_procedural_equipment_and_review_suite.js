'use strict';
const assert=require('assert'),{SIM,ECO,JD}=require('./load');
const W=SIM.create('v213-restored-regression');
const a=ECO.rollProceduralGear(W,{slot:'WEAPON',gearType:'SWORD',tier:3}),b=ECO.rollProceduralGear(W,{slot:'WEAPON',gearType:'SWORD',tier:3});
assert(a.uid&&b.uid&&a.uid!==b.uid,'each generated physical copy has a unique ID');
assert(a.procedural&&a.dur===100&&a.maxDur===100);
W.sect.gear.push(a,b);a.dur=10;
ECO.add(W,'ITEM_REPAIR_STONE_4',1);
const repaired=ECO.repairGear(W,a,'ITEM_REPAIR_STONE_4');assert(repaired.ok);assert.equal(a.maxDur,90);assert.equal(a.dur,90);
const restored=SIM.deserialize(SIM.serialize(W));
assert.equal(restored.sect.gear.find(x=>x.uid===a.uid).maxDur,90);
assert(restored.sect.gear.some(x=>x.uid===b.uid));
assert(JD.CULT.paths.CRAFT_CREATION.subPaths.some(s=>s.id==='RUNE_ARRAY_ENGRAVER'));
console.log('PASS restored v213 generated instance, best repair, distinct copy and save regression');
