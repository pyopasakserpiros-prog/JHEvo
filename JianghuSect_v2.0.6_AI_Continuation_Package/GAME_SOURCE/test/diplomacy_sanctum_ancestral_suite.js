'use strict';
const assert = require('node:assert/strict');
const { SIM, SECT, EXPLORE, CULT } = require('./load.js');
const W = SIM.create('diplomacy-regression');
const master = W.byId[W.sect.masterId];
const sect = W.world.sects[0];
W.sect.stones = 5000;
W.world.sects = [sect];
sect.attitude = 30; sect.treaty = 'NONE';
for (const key of ['banquet','tournament','seclusion','upgrade','research','drive','discipleOf','audit']) W.sect.cd[key] = W.day + 100;
W.sect.cd.diplomacy = 0;
W.rng.chance = () => true;
W.rng.float = () => 0;
SECT.masterDecision(W, master);
assert.equal(sect.treaty, 'TRADE_CARAVAN_ACCORD', 'master must sign a feasible trade accord');
W.sect.cd.diplomacy = 0;
const before = Object.values(W.sect.crystals || {}).reduce((a,b)=>a+b,0);
SECT.masterDecision(W, master);
assert.equal(sect.lastCaravanDay, W.day, 'successful exchange records the cooldown day');
assert(Object.values(W.sect.crystals || {}).reduce((a,b)=>a+b,0) > before, 'exchange delivers a crystal');
const tablet = SECT.inscribeLegacyTablet(W, master, 'test', {quiet:true});
assert(tablet && SECT.prayAtAncestralShrine(W, W.npcs[1], tablet.id), 'tablet grants blessing');
const member = W.npcs[1];
const ex = EXPLORE.departSanctum(W, [member], Object.keys(EXPLORE.SANCTUMS)[0]);
assert(ex && W.world.expeds.includes(ex), 'sanctum departure registers expedition');
ex.forceClear = true;
const sanctumOut = EXPLORE.resolveSanctum(W, ex, [member]);
assert.equal(sanctumOut.floorsCleared, 3, 'a successful sanctum run resolves all three floors');
assert.equal(sanctumOut.floorLogs.length, 3, 'every floor has a combat outcome');
assert(Object.keys(sanctumOut.catalysts).length >= 1, 'sanctum completion awards catalysts');
assert.equal(member.away, false, 'expedition members return after resolution');
assert(CULT.inspectProgressionBottleneck(W, master), 'progression bottleneck can be inspected');
const crossPathLegend = {id:'TEST_CROSS_PATH_LEGEND', nameTh:'test', legendary:true, path:'BODY', tier:1, reqTier:1, power:1};
const samePathEfficiency = globalThis.MARTIAL.skillEfficiency(master, crossPathLegend);
const originalPath = master.cult.path;
master.cult.path = 'GOD';
const crossPathEfficiency = globalThis.MARTIAL.skillEfficiency(master, crossPathLegend);
assert(crossPathEfficiency < samePathEfficiency, 'cross-path legendary compatibility affects actual combat efficiency');
master.cult.path = originalPath;
const originalBlessing = member.ancestralBlessing;
member.ancestralBlessing = null;
const pWithoutBlessing = CULT.breakthroughChance(member, {now: W.t});
member.ancestralBlessing = Object.assign({}, originalBlessing, {until: W.t + 100, breakthroughBonus: 0.12});
const pWithBlessing = CULT.breakthroughChance(member, {now: W.t});
assert(pWithBlessing > pWithoutBlessing, 'active ancestral blessing affects breakthrough odds');
member.ancestralBlessing.until = W.t - 1;
assert.equal(CULT.breakthroughChance(member, {now: W.t}), pWithoutBlessing, 'expired ancestral blessing no longer affects breakthrough odds');
member.ancestralBlessing = originalBlessing;
const restored = SIM.deserialize(SIM.serialize(W));
assert.equal(restored.world.sects[0].treaty, 'TRADE_CARAVAN_ACCORD', 'treaty survives save/load');
assert.equal(restored.world.sects[0].lastCaravanDay, W.day, 'caravan cooldown survives save/load');
assert(restored.byId[member.id].ancestralBlessing, 'active shrine blessing survives save/load');
assert(restored.world.expeds.some(x => x.kind === 'sanctum'), 'sanctum expedition survives save/load');
console.log('PASS diplomacy, exchange, shrine, sanctum departure, bottleneck smoke');
